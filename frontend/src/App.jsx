import { useCallback, useEffect, useMemo, useState } from 'react'
import { createTranscription, deleteTranscription, getTranscription, listTranscriptions, searchTranscriptions } from './api.js'
import History from './components/History.jsx'
import Icon from './components/Icon.jsx'
import Sidebar from './components/Sidebar.jsx'
import TranscriptCard from './components/TranscriptCard.jsx'
import UploadCard from './components/UploadCard.jsx'

export default function App() {
  const [activePage, setActivePage] = useState('Home')
  const [items, setItems] = useState([])
  const [selected, setSelected] = useState(null)
  const [loading, setLoading] = useState(true)
  const [busy, setBusy] = useState(false)
  const [historyError, setHistoryError] = useState('')
  const [actionError, setActionError] = useState('')
  const [query, setQuery] = useState('')

  const refresh = useCallback(async () => {
    setLoading(true)
    setHistoryError('')
    try {
      setItems(query.trim() ? await searchTranscriptions(query.trim()) : await listTranscriptions())
    } catch (error) {
      setHistoryError(error.message)
    } finally {
      setLoading(false)
    }
  }, [query])

  useEffect(() => {
    const timer = window.setTimeout(refresh, 220)
    return () => window.clearTimeout(timer)
  }, [refresh])

  const handleTranscribe = async (file) => {
    setBusy(true)
    setActionError('')
    try {
      const result = await createTranscription(file)
      setSelected(result)
      setQuery('')
      await refresh()
      setActivePage('Home')
    } catch (error) {
      setActionError(error.message)
      throw error
    } finally {
      setBusy(false)
    }
  }

  const handleView = async (item) => {
    setActionError('')
    try {
      setSelected(await getTranscription(item.id))
      setActivePage('Home')
      window.scrollTo({ top: 0, behavior: 'smooth' })
    } catch (error) {
      setActionError(error.message)
    }
  }

  const handleDelete = async (item) => {
    if (!window.confirm(`Delete "${item.title}"? This cannot be undone.`)) return
    setHistoryError('')
    try {
      await deleteTranscription(item.id)
      if (selected?.id === item.id) setSelected(null)
      await refresh()
    } catch (error) {
      setHistoryError(error.message)
    }
  }

  const pageContent = useMemo(() => {
    if (activePage === 'About') {
      return <section className="panel about-panel"><span className="eyebrow">ABOUT AUDIBLEX</span><h2>Audio, understood.</h2>
        <p>AudibleX turns your audio recordings into text you can search, revisit, and share. Recordings are transcribed by OpenAI Whisper through a secure backend connection; your API key stays on the server.</p>
        <div className="about-points"><div><strong>01</strong><span>Upload supported audio up to 25 MB.</span></div><div><strong>02</strong><span>Get a transcript generated by Whisper.</span></div><div><strong>03</strong><span>Search, copy, and manage your library.</span></div></div></section>
    }
    return (
      <>
        {activePage === 'Home' && <>
          <div className="welcome-row">
            <div><span className="eyebrow">TUESDAY, YOUR AUDIO WORKSPACE</span><h1>Make every word <span>count.</span></h1><p>Turn the moments you record into ideas you can work with.</p></div>
            <div className="welcome-orb"><span className="orb-ring ring-one" /><span className="orb-ring ring-two" /><span className="orb-center"><Icon name="audio" size={27} /></span></div>
          </div>
          <UploadCard onTranscribe={handleTranscribe} busy={busy} />
          {actionError && <div className="notice-error action-error" role="alert">{actionError}</div>}
          <TranscriptCard transcription={selected} onDismiss={() => setSelected(null)} />
        </>}
        <History items={items} loading={loading} query={query} onQueryChange={setQuery}
          onView={handleView} onDelete={handleDelete} error={historyError} />
      </>
    )
  }, [activePage, actionError, busy, handleDelete, handleView, historyError, items, loading, query, selected])

  return (
    <div className="app-shell">
      <Sidebar activePage={activePage} onNavigate={setActivePage} />
      <main className="main-content">
        <header className="topbar">
          <div className="breadcrumb"><span>Workspace</span><Icon name="chevron" size={14} /><strong>{activePage}</strong></div>
          <div className="topbar-right"><span className="system-status"><i /> All systems operational</span><span className="topbar-divider" /><button className="help-button" onClick={() => setActivePage('About')}><Icon name="info" size={16} /> Help</button></div>
        </header>
        <div className="page-content">{pageContent}</div>
        <footer className="footer"><span>© 2026 AudibleX</span><span>Made for the moments worth remembering <i>✦</i></span><span>Powered by OpenAI Whisper</span></footer>
      </main>
    </div>
  )
}
